import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const iconPath = path.join(__dirname, '../assets/images/app-icon.png');
const outPath = path.join(__dirname, '../src/lib/mwa-app-icon.ts');

/** Wallets display ~48–96px; keep payload small for MWA authorize JSON. */
const MWA_ICON_SIZE = 128;

const png = await sharp(iconPath)
  .resize(MWA_ICON_SIZE, MWA_ICON_SIZE, {
    fit: 'contain',
    background: { r: 11, g: 16, b: 27, alpha: 1 },
  })
  .png({ compressionLevel: 9 })
  .toBuffer();

const dataUri = `data:image/png;base64,${png.toString('base64')}`;

const source = `/** Auto-generated by scripts/gen-mwa-icon.mjs — do not edit by hand */\nexport const MWA_APP_ICON_DATA_URI = ${JSON.stringify(dataUri)};\n`;

fs.writeFileSync(outPath, source);
console.log(
  `Wrote ${outPath} (${MWA_ICON_SIZE}x${MWA_ICON_SIZE} PNG, ${png.length} bytes → ${dataUri.length} chars)`,
);
